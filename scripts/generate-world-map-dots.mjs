#!/usr/bin/env node
// Regenerates src/app/worldMapDots.ts from world-atlas's merged landmass
// topology (land-110m.json), converted to GeoJSON via topojson-client's
// feature(), and sampled with the point-in-polygon grid sampler in
// worldMapDotsGen.mjs. Run: node scripts/generate-world-map-dots.mjs
//
// world-atlas/topojson-client are devDependencies only — this script runs
// once at dev time; nothing under src/ imports them.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { feature } from "topojson-client";
import { sampleLandGrid } from "./worldMapDotsGen.mjs";

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = join(__dirname, "..", "src", "app", "worldMapDots.ts");
const STEP_DEG = 2;

const landTopology = require("world-atlas/land-110m.json");
const landFeature = feature(landTopology, landTopology.objects.land);
const geometry = landFeature.type === "FeatureCollection" ? landFeature.features[0].geometry : landFeature.geometry;

const points = sampleLandGrid(geometry.coordinates, STEP_DEG);

const body = points.map(([lon, lat]) => `  [${lon}, ${lat}],`).join("\n");
const output = `// Generated by scripts/generate-world-map-dots.mjs from world-atlas's
// land-110m.json (merged landmass topology, converted to GeoJSON via
// topojson-client's feature()). Each entry is a [lon, lat] pair in degrees,
// sampled on a ${STEP_DEG}° grid and kept only where it falls on land
// (ray-casting point-in-polygon test, scripts/worldMapDotsGen.mjs).
// Regenerate with: node scripts/generate-world-map-dots.mjs
// ${points.length} points at STEP_DEG = ${STEP_DEG}.
export const WORLD_MAP_DOTS: ReadonlyArray<readonly [number, number]> = [
${body}
];
`;

writeFileSync(OUTPUT_PATH, output);
console.log(`Wrote ${points.length} points to ${OUTPUT_PATH}`);
